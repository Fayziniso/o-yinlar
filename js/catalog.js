export function getGamesByAge(ageGroup) {
  return GAMES.filter((g) => g.ageGroup === ageGroup);
}

export function getGameById(id) {
  return GAMES.find((g) => g.id === id) || null;
}

export function getDailyChallengeGame(ageGroup) {
  const list = getGamesByAge(ageGroup);
  if (!list.length) return GAMES[0];
  const now = new Date();
  const daySeed = now.getFullYear() * 1000 + now.getMonth() * 40 + now.getDate();
  return list[daySeed % list.length];
}
